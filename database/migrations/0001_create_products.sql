-- 0001: products table.
--
-- Index policy: only indexes that serve the benchmarked queries are created,
-- because every extra index adds cost to POST/PUT/DELETE in all three servers.
--   * products_pkey            -> GET /products/:id, ORDER BY id for list/search
--   * products_name_trgm_idx   -> case-insensitive substring search on name (ILIKE '%q%')

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE products (
    id          BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT           NOT NULL CHECK (char_length(name) BETWEEN 1 AND 200),
    description TEXT           NOT NULL DEFAULT '' CHECK (char_length(description) <= 2000),
    category    TEXT           NOT NULL CHECK (char_length(category) BETWEEN 1 AND 100),
    price       NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    stock       INTEGER        NOT NULL CHECK (stock >= 0),
    rating      NUMERIC(2, 1)  NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX products_name_trgm_idx ON products USING gin (name gin_trgm_ops);
